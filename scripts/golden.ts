// bun scripts/golden.ts write | check | png <name> [rows]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { deflateSync } from 'node:zlib'
import { GOLDEN_CASES, fingerprint } from '../hooks/golden-cases'
import { GOLDEN } from '../hooks/golden-hashes'
import { setupFrom } from '../hooks/map'
import { paintScene, pictureFor } from '../hooks/paint/scene-paint'
import { sceneOf } from '../hooks/scene'
import { drawMap } from '../hooks/svg'

const render = (g: (typeof GOLDEN_CASES)[number]): string => drawMap(g.board, g.now, setupFrom(g.options))
const root = join(import.meta.dir, '..')

if (process.argv[2] === 'write') {
  const out = join(import.meta.dir, 'golden-out')
  mkdirSync(out, { recursive: true })
  const lines: string[] = []
  GOLDEN_CASES.forEach((g, n) => {
    const svg = render(g)
    writeFileSync(join(out, `${n}-${g.name.replace(/[^A-Za-z0-9-]/g, '_')}.svg`), svg)
    lines.push(`  ${JSON.stringify(g.name)}: '${fingerprint(svg)}',`)
  })
  writeFileSync(
    join(root, 'hooks', 'golden-hashes.ts'),
    `// Generated by scripts/golden.ts: do not edit.\nexport const GOLDEN: Readonly<Record<string, string>> = {\n${lines.join('\n')}\n}\n`,
  )
  console.log(`wrote ${GOLDEN_CASES.length} cases`)
} else if (process.argv[2] === 'check') {
  const dir = join(import.meta.dir, 'golden-out')
  let bad = 0
  GOLDEN_CASES.forEach((g, n) => {
    const svg = render(g)
    if (fingerprint(svg) === GOLDEN[g.name]) return
    bad++
    let old = ''
    try { old = readFileSync(join(dir, `${n}-${g.name.replace(/[^A-Za-z0-9-]/g, '_')}.svg`), 'utf8') } catch {}
    let at = 0
    while (at < svg.length && at < old.length && svg[at] === old[at]) at++
    console.log(`${g.name}: differs at ${at}\n  was: ${old.slice(Math.max(0, at - 80), at + 80)}\n  now: ${svg.slice(Math.max(0, at - 80), at + 80)}`)
  })
  console.log(`${bad} mismatches`)
  process.exit(bad === 0 ? 0 : 1)
} else if (process.argv[2] === 'png' && process.argv[3] !== undefined) {
  // One case as the pixel painter draws it at the case's own moment, to look at beside its SVG.
  const name = process.argv[3]
  const rows = process.argv[4] === undefined ? 20 : Number(process.argv[4])
  const g = GOLDEN_CASES.find(c => c.name === name)
  if (g === undefined || !Number.isInteger(rows) || rows <= 0) {
    console.log(g === undefined ? `no case named ${name}` : `rows must be a whole number, not ${process.argv[4]}`)
    process.exit(2)
  }
  const setup = setupFrom(g.options)
  const picture = pictureFor(rows)
  const frame = paintScene(sceneOf(g.board, g.now, setup), g.now, picture, { light: false, colors: setup.colors })
  const out = join(import.meta.dir, 'golden-out')
  mkdirSync(out, { recursive: true })
  const file = join(out, `${name.replace(/[^A-Za-z0-9-]/g, '_')}-${rows}.png`)
  writeFileSync(file, png(frame.width, frame.height, frame.toStraight()))
  console.log(`wrote ${file} (${frame.width}×${frame.height})`)
} else {
  console.log('usage: bun scripts/golden.ts write|check|png <name> [rows]')
  process.exit(2)
}

/** Straight RGBA as a PNG: 8 bits a channel, no filtering, one IDAT. */
function png(width: number, height: number, rgba: Uint8Array): Uint8Array {
  const stride = width * 4
  const raw = new Uint8Array((stride + 1) * height)
  for (let y = 0; y < height; y++) raw.set(rgba.subarray(y * stride, (y + 1) * stride), y * (stride + 1) + 1)
  const header = new Uint8Array(13)
  const view = new DataView(header.buffer)
  view.setUint32(0, width)
  view.setUint32(4, height)
  header.set([8, 6, 0, 0, 0], 8)
  const table = crcTable()
  const parts = [new Uint8Array([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', header, table), chunk('IDAT', deflateSync(raw), table), chunk('IEND', new Uint8Array(0), table)]
  const all = new Uint8Array(parts.reduce((n, p) => n + p.length, 0))
  let at = 0
  for (const p of parts) {
    all.set(p, at)
    at += p.length
  }
  return all
}

function chunk(type: string, data: Uint8Array, table: number[]): Uint8Array {
  const out = new Uint8Array(12 + data.length)
  const view = new DataView(out.buffer)
  view.setUint32(0, data.length)
  for (let i = 0; i < 4; i++) out[4 + i] = type.charCodeAt(i)
  out.set(data, 8)
  view.setUint32(8 + data.length, crc32(out.subarray(4, 8 + data.length), table))
  return out
}

// Made per picture: the commands above run before a top-level constant down here would be set.
function crcTable(): number[] {
  return Array.from({ length: 256 }, (_, n) => {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    return c >>> 0
  })
}

function crc32(bytes: Uint8Array, table: number[]): number {
  let c = 0xffffffff
  for (const b of bytes) c = table[(c ^ b) & 0xff]! ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}

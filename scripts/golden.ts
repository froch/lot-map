// bun scripts/golden.ts write | check
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { GOLDEN_CASES, fingerprint } from '../hooks/golden-cases'
import { GOLDEN } from '../hooks/golden-hashes'
import { drawMap, setupFrom } from '../hooks/map'

const render = (g: (typeof GOLDEN_CASES)[number]): string => drawMap(g.board, g.now, setupFrom(g.options))
const root = join(import.meta.dir, '..')

if (process.argv[2] === 'write') {
  const out = join(import.meta.dir, 'golden-out')
  mkdirSync(out, { recursive: true })
  const lines: string[] = []
  GOLDEN_CASES.forEach((g, n) => {
    const svg = render(g)
    writeFileSync(join(out, `${n}-${g.name.replace(/[^A-Za-z0-9-]/g, '_')}.svg`), svg)
    lines.push(`  ${JSON.stringify(g.name)}: '${fingerprint(svg)}',`)
  })
  writeFileSync(
    join(root, 'hooks', 'golden-hashes.ts'),
    `// Generated by scripts/golden.ts: do not edit.\nexport const GOLDEN: Readonly<Record<string, string>> = {\n${lines.join('\n')}\n}\n`,
  )
  console.log(`wrote ${GOLDEN_CASES.length} cases`)
} else if (process.argv[2] === 'check') {
  const dir = join(import.meta.dir, 'golden-out')
  let bad = 0
  GOLDEN_CASES.forEach((g, n) => {
    const svg = render(g)
    if (fingerprint(svg) === GOLDEN[g.name]) return
    bad++
    let old = ''
    try { old = readFileSync(join(dir, `${n}-${g.name.replace(/[^A-Za-z0-9-]/g, '_')}.svg`), 'utf8') } catch {}
    let at = 0
    while (at < svg.length && at < old.length && svg[at] === old[at]) at++
    console.log(`${g.name}: differs at ${at}\n  was: ${old.slice(Math.max(0, at - 80), at + 80)}\n  now: ${svg.slice(Math.max(0, at - 80), at + 80)}`)
  })
  console.log(`${bad} mismatches`)
  process.exit(bad === 0 ? 0 : 1)
} else {
  console.log('usage: bun scripts/golden.ts write|check')
  process.exit(2)
}
